"""Generate canonical response schemas and TypeScript types; --check rejects drift."""
import argparse
from dataclasses import fields, is_dataclass
import json
from pathlib import Path
import sys
from types import UnionType
from typing import Any, Literal, NotRequired, Required, Union, get_args, get_origin, get_type_hints, is_typeddict

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
from symbiknow.core import contracts  # noqa: E402
from symbiknow.core import wire_contracts  # noqa: E402


def annotation_shape(annotation):
    origin, args = get_origin(annotation), get_args(annotation)
    if origin in (NotRequired, Required):
        return annotation_shape(args[0])
    if annotation is Any:
        return "unknown", {}
    primitives = {str: ("string", "string"), int: ("number", "integer"),
                  float: ("number", "number"), bool: ("boolean", "boolean"),
                  type(None): ("null", "null")}
    if annotation in primitives:
        ts, schema = primitives[annotation]
        return ts, {"type": schema}
    if origin in (Union, UnionType):
        shapes = [annotation_shape(arg) for arg in args]
        return " | ".join(ts for ts, _ in shapes), {"anyOf": [schema for _, schema in shapes]}
    if origin is Literal:
        return " | ".join(json.dumps(arg) for arg in args), {"enum": list(args)}
    if origin is list:
        ts, schema = annotation_shape(args[0])
        return f"Array<{ts}>", {"type": "array", "items": schema}
    if origin is dict:
        if args[0] is not str:
            raise TypeError("Wire objects require string keys")
        ts, schema = annotation_shape(args[1])
        return f"Record<string, {ts}>", {"type": "object", "additionalProperties": schema}
    if is_dataclass(annotation) or is_typeddict(annotation):
        return annotation.__name__, {"$ref": "#/$defs/" + annotation.__name__}
    raise TypeError(f"Unsupported wire annotation: {annotation!r}")


def generate():
    identities = [contracts.DocumentReference, contracts.EvidenceReference,
                  contracts.ProcessingDescriptor, contracts.RevisionToken]
    models = identities + [value for name, value in vars(wire_contracts).items()
                           if is_typeddict(value) and name != "IdentityFields"
                           and value.__module__ == wire_contracts.__name__]
    lines = ["// Generated by scripts/contracts/generate.py; edit backend/symbiknow/core/contracts.py or backend/symbiknow/core/wire_contracts.py.\n"]
    schemas = {}
    for model in models:
        hints = get_type_hints(model, include_extras=True)
        required = {field.name for field in fields(model)} if is_dataclass(model) else model.__required_keys__
        properties = {}
        lines.append(f"export type {model.__name__} = {{")
        for name, annotation in hints.items():
            ts, schema = annotation_shape(annotation)
            lines.append(f"  {name}{'' if name in required else '?'}: {ts};")
            properties[name] = schema
        lines.append("};\n")
        schemas[model.__name__] = {"type": "object", "properties": properties,
                                  "required": [name for name in hints if name in required],
                                  "additionalProperties": not is_dataclass(model)}
    return {
        ROOT / "frontend/src/shared/api/contracts.generated.ts": "\n".join(lines),
        ROOT / "backend/symbiknow/schemas/contracts.json": json.dumps(
            {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": schemas}, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Generated contract drift: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
