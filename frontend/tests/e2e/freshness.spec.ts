import { test, expect } from "@playwright/test";
import fs from "node:fs/promises";

test("manual freshness scan shows saved evidence and review decisions", async ({ page }) => {
  test.setTimeout(90000);
  await page.goto("/");
  const initial = await (await page.request.get("/api/freshness")).json();
  expect(initial.scan).toBeNull();
  await page.getByRole("button", { name: "Check for outdated documents" }).click();
  const dialog = page.getByRole("dialog", { name: "Document freshness review" });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByText("No scan yet.", { exact: false })).toBeVisible();
  await dialog.getByText("Optional reference", { exact: true }).click();
  await expect(dialog.getByLabel("Trusted reference document").locator("option")).toHaveCount(8);
  await dialog.getByText("Optional reference", { exact: true }).click();
  const start = page.waitForResponse(r => r.url().endsWith("/api/freshness") && r.request().method() === "POST");
  await dialog.getByRole("button", { name: "Scan all documents", exact: true }).click();
  const id = (await (await start).json()).scan_id;
  await expect.poll(async () => {
    const state = await (await page.request.get("/api/freshness?scan_id=" + id)).json();
    return state.scan.status;
  }, { timeout: 60000 }).toMatch(/completed|partial/);
  await expect(dialog.locator(".freshness-finding").first()).toBeVisible({ timeout: 15000 });
  await expect(dialog.locator(".freshness-progress")).toContainText("passages searched");
  await expect(dialog.locator(".freshness-progress")).toContainText("candidate pairs processed");
  const finding = dialog.locator(".freshness-finding").first();
  await expect(finding.getByRole("heading", { name: /Conflicting/ })).toBeVisible();
  await expect(finding.locator("blockquote")).toHaveCount(2);
  await finding.getByText("Why this label?", { exact: true }).click();
  await expect(finding.getByText(/Claim detail: specific/)).toBeVisible();
  await expect(finding.getByText(/They are not proof that a document is correct/)).toBeVisible();
  await expect(dialog.getByLabel("Freshness label", { exact: true }).locator("option")).toHaveCount(5);
  const quickActions = finding.getByRole("group", { name: "Quick actions for Conflicting", exact: true });
  await expect(quickActions).toBeVisible();
  await expect(finding.getByRole("button", { name: "Open document", exact: true })).toHaveCount(2);
  await expect(finding.getByRole("button", { name: "Upload corrected version", exact: true })).toHaveCount(2);
  await finding.getByLabel("Review note for Conflicting").fill("Browser review fixture");
  await quickActions.getByRole("button", { name: "Dismiss", exact: true }).click();
  await expect(finding.getByRole("heading")).toContainText("dismissed");
  await quickActions.getByRole("button", { name: "Reopen", exact: true }).click();
  await expect(finding.getByRole("heading")).toContainText("pending");
  await quickActions.getByRole("button", { name: "Keep as historical", exact: true }).click();
  await expect(finding.getByRole("heading")).toContainText("historical");
  await quickActions.getByRole("button", { name: "Confirm", exact: true }).click();
  await expect(finding.getByRole("heading")).toContainText("confirmed");
  await fs.mkdir("../artifacts/freshness-implementation", { recursive: true });
  await page.screenshot({ path: "../artifacts/freshness-implementation/review-desktop.png", fullPage: true });
  await dialog.getByRole("button", { name: "Close freshness review" }).click();
  await page.reload();
  await page.getByRole("button", { name: /Check for outdated documents/ }).click();
  await expect(dialog.locator(".freshness-finding").first().getByRole("heading")).toContainText("confirmed");
  const before = await (await page.request.get("/api/freshness")).json();
  expect(before.scan.scan_id).toBe(id); // Opening/reloading did not start another scan.
  await dialog.locator(".freshness-finding").first().getByRole("button", { name: "Recheck", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "Cancel scan", exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Cancel scan", exact: true }).click();
  await expect(dialog.locator(".freshness-progress strong")).toHaveText("cancelled");
  await page.setViewportSize({ width: 700, height: 900 });
  await expect(dialog).toBeVisible();
  expect(await dialog.evaluate(e => e.scrollWidth <= e.clientWidth + 1)).toBeTruthy();
});
